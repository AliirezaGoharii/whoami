#!/usr/bin/env python3
"""Build the portable portfolio from its HTML, CSS, JavaScript and SVG sources."""
from pathlib import Path
import argparse
import sys
import tempfile
import textwrap

ROOT = Path(__file__).resolve().parent


def render():
    def read(name):
        return (ROOT / name).read_text(encoding="utf-8").strip()
    page = read("src/index.html")
    scripts = "\n\n".join(read(name) for name in ("src/scripts/app.js", "src/scripts/ascii.js"))
    includes = {
        "bootstrap": "<script>\n" + textwrap.indent(read("src/scripts/bootstrap.js"), "    ") + "\n    </script>",
        "styles": "<style>\n" + textwrap.indent(read("src/styles.css"), "        ") + "\n    </style>",
        "scripts": "<script>\n" + scripts + "\n</script>",
        "zenith": read("zenith.svg"),
    }
    for name, content in includes.items():
        marker = f"<!-- @{name} -->"
        if page.count(marker) != 1:
            raise ValueError(f"Expected exactly one {marker} in src/index.html")
        page = page.replace(marker, content)
    return page.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by build.py. Edit src/ and rebuild. -->", 1) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that index.html matches the sources.")
    args = parser.parse_args()
    result = render()
    output = ROOT / "index.html"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != result:
            print("index.html is out of date. Run: python3 build.py", file=sys.stderr)
            return 1
        print("PASS index.html matches the sources")
    else:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=ROOT, prefix=".index-", suffix=".tmp", delete=False) as temporary:
            temporary.write(result)
        temporary_path = Path(temporary.name)
        try:
            temporary_path.chmod(0o644)
            temporary_path.replace(output)
        finally:
            temporary_path.unlink(missing_ok=True)
        print(f"Built {output.name} ({len(result.encode('utf-8')):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
